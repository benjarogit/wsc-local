"""WoltLab tool preconditions and recovery lifecycle, without external downloads."""
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'workbench'))
import cli

class WoltLabToolTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.root=Path(self.temp.name)
        (self.root/'site').mkdir();(self.root/'site/global.php').write_text('<?php')
        self.reader=patch.object(cli,'read_project',return_value=({'url':'https://test.localhost:8081'},self.root,self.root/'secret'))
        self.reader.start()
    def tearDown(self):
        self.reader.stop();self.temp.cleanup()

    def test_recovery_rejects_html_before_backup_and_file_creation(self):
        with patch.object(cli.urllib.request,'urlopen',return_value=io.BytesIO(b'<html>not a script</html>')),patch.object(cli,'snapshot') as snapshot:
            with self.assertRaises(ValueError):cli.recovery_install('test',True)
            snapshot.assert_not_called()
        self.assertFalse((self.root/'site/wsc-recovery.php').exists())

    def test_recovery_can_be_installed_and_removed_with_integrity_check(self):
        content=b'<?php /* official tool fixture */'
        with patch.object(cli.urllib.request,'urlopen',return_value=io.BytesIO(content)),patch.object(cli,'snapshot',return_value=self.root/'snapshots/one') as snapshot:
            result=cli.recovery_install('test',True)
            snapshot.assert_called_once_with('test')
        self.assertIn('https://test.localhost:8081/wsc-recovery.php',result)
        self.assertEqual(content,(self.root/'site/wsc-recovery.php').read_bytes())
        manifest=json.loads((self.root/'recovery-tool.json').read_text())
        self.assertEqual(cli.RECOVERY_URL,manifest['source'])
        cli.recovery_remove('test',True)
        self.assertFalse((self.root/'site/wsc-recovery.php').exists())
        self.assertFalse((self.root/'recovery-tool.json').exists())

    def test_recovery_also_removes_only_recognized_authentication_files(self):
        with patch.object(cli.urllib.request,'urlopen',return_value=io.BytesIO(b'<?php')),patch.object(cli,'snapshot',return_value=self.root/'snapshot'):
            cli.recovery_install('test',True)
        auth=self.root/'site/wsc-recovery-auth.php';auth.write_text('<?php changed')
        with self.assertRaises(ValueError):cli.recovery_remove('test',True)
        self.assertTrue((self.root/'site/wsc-recovery.php').exists())
        auth.write_text('<?php exit; /* --- DO NOT EDIT THIS FILE --- */ ?>\n1793200000\n'+'a'*40)
        cli.recovery_remove('test',True)
        self.assertFalse(auth.exists())
        self.assertFalse((self.root/'site/wsc-recovery.php').exists())

    def test_changed_recovery_file_is_preserved(self):
        with patch.object(cli.urllib.request,'urlopen',return_value=io.BytesIO(b'<?php')),patch.object(cli,'snapshot',return_value=self.root/'snapshot'):
            cli.recovery_install('test',True)
        target=self.root/'site/wsc-recovery.php';target.write_text('<?php changed')
        with self.assertRaises(ValueError):cli.recovery_remove('test',True)
        self.assertTrue(target.exists())

    def test_tool_preparation_requires_an_installed_suite(self):
        (self.root/'site/global.php').unlink()
        with patch.object(cli,'snapshot') as snapshot:
            for topic in ('domain','directory','migration'):
                with self.subTest(topic=topic),self.assertRaises(ValueError):cli.guide('test',topic)
            with self.assertRaises(ValueError):cli.recovery_install('test',True)
            snapshot.assert_not_called()

    def test_guides_create_the_right_backup_and_explain_scope(self):
        for topic in ('domain','directory','migration'):
            with self.subTest(topic=topic),patch.object(cli,'snapshot',return_value=self.root/'backup') as snapshot:
                text=cli.guide('test',topic)
                snapshot.assert_called_once_with('test',export=topic=='migration')
                self.assertIn('https://manual.woltlab.com/',text)
                self.assertIn('backup',text)
